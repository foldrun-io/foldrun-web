#!/usr/bin/env node
// Writes server/openapi-routes.ts: every route under app/api (and /s/<token>),
// the methods its route.ts exports, and the one-line description its row in
// foldrun-docs/api.md gives it. The same two sources the "every API route is
// in docs/api.md" guard in tests/consistency.test.ts reads — so the spec at
// /api/openapi.json cannot list a route that does not exist, or miss one that
// does (tests/openapi.test.ts regenerates in memory and compares).
//
//   node scripts/gen-openapi.mjs            rewrite server/openapi-routes.ts
//   node scripts/gen-openapi.mjs --check    exit 1 if it is stale

import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const webRoot = path.join(here, "..");

/** @returns {{ path: string, methods: string[] }[]} */
export function walkRoutes(root = webRoot) {
  const apiRoot = path.join(root, "app/api");
  const out = [];
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.name === "route.ts") {
        const rel = "/api/" + path.relative(apiRoot, dir).split(path.sep).join("/");
        // The operator console's routes (28 Oct 2026: its own container,
        // private code) are not part of the public API or its spec.
        if (CONSOLE_ROUTE.test(rel)) continue;
        const src = fs.readFileSync(full, "utf8");
        out.push({ path: rel.replace(/\/$/, ""), methods: methodsOf(src), idempotent: idempotentOf(src) });
      }
    }
  };
  walk(apiRoot);
  const share = path.join(root, "app/s/[token]/route.ts");
  if (fs.existsSync(share)) out.push({ path: "/s/[token]", methods: methodsOf(fs.readFileSync(share, "utf8")), idempotent: [] });
  return out.sort((a, b) => a.path.localeCompare(b.path));
}

function methodsOf(src) {
  const order = ["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD"];
  const found = new Set([...src.matchAll(/^export (?:async )?function (GET|POST|PUT|PATCH|DELETE|HEAD)\b/gm)].map((m) => m[1]));
  return order.filter((m) => found.has(m));
}

/** The methods that answer through server/idempotency.ts. */
function idempotentOf(src) {
  return [...src.matchAll(/^export (?:async )?function (POST|PUT|PATCH|DELETE)\([^)]*\)[^{]*\{\s*return idempotent\(/gm)].map((m) => m[1]);
}

/** The console's own routes — in a hosted tree only, and never described here. */
export const CONSOLE_ROUTE = /^\/api\/(admin|support)(\/|$)/;

/** `[workspace]` → `{workspace}`, `[...path]` → `{path}`. */
export const openapiPath = (p) => p.replace(/\[(?:\.\.\.)?([a-zA-Z]+)\]/g, "{$1}");

/** The row's third cell in api.md, by route shape. */
export function summaries(apiMd) {
  const rows = new Map();
  for (const line of apiMd.split("\n")) {
    if (!line.startsWith("|")) continue;
    const cells = line.split("|").map((c) => c.trim());
    const routeCell = (cells[1] ?? "").replace(/`/g, "").replace(/\?[^\s·]*/g, "");
    if (!routeCell.startsWith("/")) continue;
    const text = (cells[3] ?? "").replace(/`/g, "").replace(/\s+/g, " ").trim();
    for (const r of routeCell.split(/\s*·\s*/)) {
      const shape = r.replace(/<[a-zA-Z]+>/g, "<>");
      if (!rows.has(shape) && text) rows.set(shape, text.length > 240 ? text.slice(0, 237) + "…" : text);
    }
  }
  return rows;
}

export function collect(root = webRoot, apiMd = readApiMd(root)) {
  const rows = summaries(apiMd);
  return walkRoutes(root).map((r) => {
    const shape = r.path.replace(/\[[^\]]+\]/g, "<>");
    // A row may be written with a prefix the route shape omits (/s/<token>).
    let summary = rows.get(shape);
    if (!summary) for (const [k, v] of rows) if (k.endsWith(shape)) { summary = v; break; }
    return { path: openapiPath(r.path), methods: r.methods, ...(r.idempotent.length ? { idempotent: r.idempotent } : {}), summary: summary ?? "" };
  });
}

function readApiMd(root) {
  try {
    return fs.readFileSync(path.join(root, "../foldrun-docs/api.md"), "utf8");
  } catch {
    return "";
  }
}

export function render(routes) {
  return `// GENERATED by scripts/gen-openapi.mjs from app/api and foldrun-docs/api.md.
// Do not edit: run \`node scripts/gen-openapi.mjs\`. tests/openapi.test.ts fails
// when a route is added or removed without regenerating.

export interface RouteEntry {
  path: string;
  methods: string[];
  /** Methods that honour Idempotency-Key. */
  idempotent?: string[];
  summary: string;
}

export const ROUTES: RouteEntry[] = [
${routes.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`;
}

const target = path.join(webRoot, "server/openapi-routes.ts");
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const text = render(collect());
  if (process.argv.includes("--check")) {
    const now = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (now !== text) {
      console.error("server/openapi-routes.ts is stale — run node scripts/gen-openapi.mjs");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(target, text);
    console.log(`wrote ${path.relative(process.cwd(), target)}`);
  }
}
